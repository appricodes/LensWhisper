private fun HelpScreen(onClose: () -> Unit) {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(24.dp)
            .verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(20.dp)
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            Text(text = "Help", fontSize = 26.sp, style = MaterialTheme.typography.titleLarge)
            TextButton(onClick = onClose) { Text("Close", fontSize = 18.sp) }
        }

        Text(
            text = "Everything in LensWhisper runs on your own phone. Your photos are never uploaded "
                + "and we never see them.",
            fontSize = 18.sp
        )
        Text(
            text = "Basic Models is built in and needs no download. Detect Objects and Object and "
                + "Colour Detection use a dedicated on-device detector to name up to 25 objects "
                + "(and their colours) at once. Explore opens the photo full-screen so you can move "
                + "a finger over it and hear what's there, or tap once for a list of everything "
                + "found and roughly where it is.",
            fontSize = 18.sp
        )
        Text(
            text = "Read Text reads any text in view, and Light Level plays a tone matching the "
                + "brightness in front of the camera. Tap a button for one reading, or hold it for "
                + "continuous updates.",
            fontSize = 18.sp
        )
        Text(
            text = "The Advanced AI models give fuller, conversational descriptions and can answer "
                + "your own spoken questions. Each has to be downloaded once, and they differ a lot "
                + "in accuracy and speed — open Manage Advanced AI Models to read what each one is "
                + "good and bad at before choosing.",
            fontSize = 18.sp
        )
        Text(
            text = "The camera is only switched on for the instant a photo is taken. If you turn the "
                + "flash on, it fires at that moment rather than staying lit.",
            fontSize = 18.sp
        )
        Text(
            text = "All descriptions are generated by AI and are often wrong. Never rely on them for "
                + "medicines, money, documents, food, or moving around safely — see Legal "
                + "Information in the More menu for the full notice.",
            fontSize = 18.sp
        )
    }
}
